"""Offline build-input contracts; no compiler, Wine, network, account or game."""
import importlib.util, tempfile, unittest, json, re
from unittest.mock import patch
from pathlib import Path
spec=importlib.util.spec_from_file_location('fh5_build',Path(__file__).with_name('build.py'))
build=importlib.util.module_from_spec(spec);spec.loader.exec_module(build)
class Inputs(unittest.TestCase):
    def test_dedicated_runtime_lock_matches_pack_even_when_shared_lock_differs(self):
        lock=json.loads((build.PACK/'source.lock.json').read_text())
        dedicated=build.runtime_lock_file(lock)
        self.assertEqual(dedicated,Path(build.__file__).with_name('runtime-patches.lock.json'))
        for entry in json.loads(dedicated.read_text())['patches']:
            self.assertEqual(build.sha(build.REPO/entry['file']),entry['sha256'])
        with tempfile.TemporaryDirectory() as folder, patch.object(build,'REPO',Path(folder)):
            shared=build.REPO/'scripts/runtime-patches.lock.json';shared.parent.mkdir();shared.write_text('different shared runtime')
            self.assertEqual(build.runtime_lock_file(lock),dedicated)

    def test_nvapi_provider_identity_matches_the_selected_engine_pin(self):
        pack=build.PACK
        descriptor=pack/('manifest.json' if (pack/'manifest.json').exists() else 'verification.json')
        manifest=json.loads(descriptor.read_text())
        header=(pack/'source/shim/nvapi_provider.h').read_text()
        values=re.search(r'fh5_nvapi_provider_digest\[32\] = \{(.*?)\}',header,re.S).group(1)
        digest=bytes(int(v,16) for v in re.findall(r'0x([0-9a-f]{2})',values)).hex()
        self.assertEqual(digest,manifest['engineFiles']['lib/apple_gptk/wine/x86_64-windows/nvapi64.dll'])
        self.assertIn('#define FH5_NVAPI_PROVIDER_SIZE 200256u',header)
    def test_relative_and_absolute_sdk_includes_map_to_the_same_fresh_source(self):
        with tempfile.TemporaryDirectory() as name:
            root=Path(name);sdk=root/'sdk';old=root/'wine-src/dlls/xgameruntime';new=root/'fresh/runtime';out=root/'output'
            relative='-I../wine-src/dlls/xgameruntime'
            a=build.sdk_include(relative,sdk,old,new,out)
            b=build.sdk_include('-I'+str(old),sdk,old,new,out)
            self.assertEqual(a,b)
            self.assertEqual((out/a[2:]).resolve(),new.resolve())
            self.assertEqual(build.sdk_include('-Iinclude',sdk,old,new,out),'-I'+str((sdk/'include').resolve()))
    def test_header_path_is_provenance_only_and_abi_bytes_are_kept(self):
        with tempfile.TemporaryDirectory() as name:
            root=Path(name);a=root/'a.h';b=root/'b.h'
            template='/*** Autogenerated by WIDL 11.0 from %sdlls/xgameruntime/xstore.idl - Do not edit ***/\nstruct ABI { int x; };\n'
            a.write_text(template%'/one/SDK path/');b.write_text(template%'../../different-source/')
            expected=build.sdk_digest(a,'dlls/xgameruntime/xstore.h')
            self.assertEqual(expected,build.sdk_digest(b,'dlls/xgameruntime/xstore.h'))
            b.write_text((template%'../../different-source/').replace('int x','long long x'))
            self.assertNotEqual(expected,build.sdk_digest(b,'dlls/xgameruntime/xstore.h'))
            with self.assertRaises(ValueError):build.sdk_digest(a,'dlls/xgameruntime/xuser.h')
    def test_unknown_header_and_changed_binary_resource_are_rejected_or_distinct(self):
        with tempfile.TemporaryDirectory() as name:
            p=Path(name)/'input';p.write_bytes(b'not a WIDL header')
            with self.assertRaises(ValueError):build.sdk_digest(p,'include/windows.data.json.h')
            first=build.sdk_digest(p,'classes_r.res');p.write_bytes(b'changed resource')
            self.assertNotEqual(first,build.sdk_digest(p,'classes_r.res'))
if __name__=='__main__':unittest.main()
