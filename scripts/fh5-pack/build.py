"""Build the FH5 source pack. Never installs a pack or launches a game/account."""
import argparse, gzip, hashlib, io, json, os, re, shlex, shutil, subprocess, tarfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PACK = REPO / 'assets/fh5-preview'

def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def check(root, values):
    for name, expected in values.items():
        if sha(root / name) != expected: raise ValueError('Source mismatch: ' + name)
def execute(args, cwd, capture=False, env=None):
    return subprocess.run(list(map(str,args)),cwd=cwd,env=env,check=True,
                          stdout=subprocess.PIPE if capture else None,
                          stderr=subprocess.PIPE if capture else None).stdout

def runtime_lock_file(lock):
    file=Path(__file__).with_name('runtime-patches.lock.json')
    if sha(file) != lock['runtimeSourceLockSHA256']: raise ValueError('FH5 runtime lock changed')
    return file

def reconstruct(mirror, output, lock):
    runtime=json.loads(runtime_lock_file(lock).read_text())
    archive=execute(['git','-C',mirror,'archive','--format=tar','--prefix=dlls/xgameruntime/',runtime['sources']['xgameruntime']['commit']],REPO,True)
    output.mkdir()
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar: tar.extractall(output,filter='data')
    env={**os.environ,'GIT_CEILING_DIRECTORIES':str(output.parent)}
    for patch in runtime['patches']:
        file=REPO/patch['file']
        if sha(file)!=patch['sha256']:raise ValueError('Patch checksum mismatch')
        if patch.get('repository'):continue
        execute(['git','apply','--include=dlls/xgameruntime/*',file],output,env=env)
    check(output,runtime['expectedXgameruntimeSources'])
    execute(['git','apply',PACK/'source/runtime.patch'],output,env=env)
    check(output,lock['runtimeTargetSHA256'])

def sdk_digest(file, relative):
    data=file.read_bytes()
    if str(relative).endswith('.h'):
        # WIDL records the input checkout path only in its first-line provenance
        # comment. Keep its version and every ABI byte; normalize that path alone.
        first, newline, body=data.partition(b'\n')
        prefix, marker, rest=first.partition(b' from ')
        original, suffix, end=rest.partition(b' - Do not edit ***/')
        expected=str(Path(relative).with_suffix('.idl')).encode()
        if not first.startswith(b'/*** Autogenerated by WIDL ') or not marker or not suffix or end or not original.endswith(expected):
            raise ValueError('Unknown generated SDK header provenance: '+str(relative))
        data=prefix+marker+expected+suffix+newline+body
    return hashlib.sha256(data).hexdigest()

def sdk_include(token, sdk_build, old_source, new_source, cwd):
    old_source=old_source.resolve();new_source=new_source.resolve()
    include=(sdk_build/token[2:]).resolve()
    if include.is_relative_to(old_source):
        return '-I'+os.path.relpath(new_source/include.relative_to(old_source),cwd.resolve())
    return '-I'+str(include)

def verification_descriptor(manifest, receipt):
    descriptor={key:manifest[key] for key in ['schema','id','storeId','version','buildTag','engineFiles']}
    descriptor.update(sourceReleaseDescriptor=1,sourceLockSHA256=receipt['sourceLockSHA256'],files=receipt['files'])
    return descriptor

def compile_runtime(source, sdk_source, sdk_build, output, lock, env):
    # Maintainer SDK input: the pinned Wine tree with its generated PE headers,
    # compiler driver/import libraries and XML archive. Every runtime C object is
    # rebuilt from the reconstructed sources; no cached runtime object is reused.
    actual=execute(['git','-C',sdk_source,'rev-parse','HEAD'],REPO,True).decode().strip()
    if actual!=lock['wineCommit']:raise ValueError('SDK is not the pinned Wine revision')
    if lock.get('sdkInputPathPolicy')!='widl-provenance-relative-v1':raise ValueError('Unknown SDK path policy')
    for relative,expected in lock['sdkGeneratedHeaders'].items():
        if sdk_digest(sdk_build/relative,relative)!=expected:raise ValueError('Generated SDK input changed: '+relative)
    # Read the already-generated SDK rules without asking make to regenerate
    # configuration or dependencies in the caller's SDK tree.
    makefile=(sdk_build/'Makefile').read_text().replace('\\\n',' ')
    variables=dict(re.findall(r'^([A-Za-z0-9_]+) = (.*)$',makefile,re.M))
    def rule(target):
        active=False
        for line in makefile.splitlines():
            if line.startswith(target+':'):active=True;continue
            if active and line.startswith('\t'):
                text=line.strip().replace('$@',target)
                for _ in range(8):
                    if '$(' not in text:break
                    text=re.sub(r'\$\(([A-Za-z0-9_]+)\)',lambda m:variables[m[1]],text)
                if '$' in text:raise ValueError('Unsupported SDK recipe variables')
                return shlex.split(text)
            if line and not line.startswith((' ','\t')):active=False
        raise ValueError('Missing generated SDK rule: '+target)
    cc=rule('dlls/xgameruntime/x86_64-windows/xuser.o')
    link=rule('dlls/xgameruntime/x86_64-windows/xgameruntime.dll')
    # XML has diagnostic __FILE__ strings even after stripping. Rebuild its
    # archive from pinned Git objects instead of inheriting SDK checkout paths.
    xml_source=output.parent/'source/wine-libraries'
    xml_source.mkdir()
    archive=execute(['git','-C',sdk_source,'archive','--format=tar',lock['wineCommit'],'libs/xml2'],REPO,True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:tar.extractall(xml_source,filter='data')
    xml=xml_source/'libs/xml2';xml_objects=output/'xml-objects';xml_objects.mkdir()
    xml_files=re.findall(r'\b([A-Za-z][A-Za-z0-9_]*\.c)\b',(xml/'Makefile.in').read_text())
    for name in xml_files:
        target='libs/xml2/x86_64-windows/'+Path(name).stem+'.o'
        args=[]
        for token in rule(target):
            if token in ['-g','-gdwarf-4']:continue
            if token==target:token=Path(name).stem+'.o'
            elif not token.startswith('-') and (sdk_build/token).resolve()==sdk_source/'libs/xml2'/name:token=os.path.relpath(xml/name,xml_objects)
            elif token.startswith('-I'):token=sdk_include(token,sdk_build,sdk_source/'libs/xml2',xml,xml_objects)
            args.append(token)
        execute(args+['-ffile-prefix-map='+str(sdk_source)+'=/wine-source'],xml_objects,env=env)
    xml_archive=output/'libxml2.a'
    execute(['x86_64-w64-mingw32-ar','rcD',xml_archive,*[xml_objects/(Path(name).stem+'.o') for name in xml_files]],REPO,env=env)
    original=sdk_source/'dlls/xgameruntime';current=source/'dlls/xgameruntime'
    files=re.findall(r'\b([a-z][a-z0-9_]*\.c)\b',(current/'Makefile.in').read_text())
    objects={}
    def relative(path):return os.path.relpath(path,sdk_build)
    for name in files:
        obj=output/(Path(name).stem+'.o');args=[]
        for token in cc:
            if token in ['-g','-gdwarf-4']:continue
            if token=='dlls/xgameruntime/x86_64-windows/xuser.o':token=obj.name
            elif not token.startswith('-') and (sdk_build/token).resolve()==original/'xuser.c':token=os.path.relpath(current/name,output)
            elif token.startswith('-I'):token=sdk_include(token,sdk_build,original,current,output)
            args.append(token)
        args += ['-ffile-prefix-map='+str(sdk_source)+'=/wine-source','-ffile-prefix-map='+str(source)+'=/runtime-source']
        execute(args,output,env=env);objects[name[:-2]+'.o']=obj
    args=[]
    for token in link:
        if token=='-Wl,--build-id':continue  # winegcc otherwise re-enables it after user linker flags
        if token=='dlls/xgameruntime/x86_64-windows/xgameruntime.dll':token=relative(output/'xgameruntime.dll')
        elif not token.startswith('-') and (sdk_build/token).resolve()==original/'xgameruntime.spec':token=relative(current/'xgameruntime.spec')
        elif token=='libs/xml2/x86_64-windows/libxml2.a':token=relative(xml_archive)
        elif token.startswith('dlls/xgameruntime/x86_64-windows/') and token.endswith('.o'):token=relative(objects[Path(token).name])
        args.append(token)
    # SDK support objects contain build-path debug data. GNU's PE CodeView
    # build ID hashes that data before stripping; omit that diagnostic ID.
    execute(args+['-Wl,--no-insert-timestamp','-Wl,--build-id=none'],sdk_build,env=env)
    execute(['x86_64-w64-mingw32-strip','--strip-debug',output/'xgameruntime.dll'],REPO,env=env)
    # JSON array support is a required runtime dependency. Build it from the
    # same pinned Wine revision instead of trusting a stock Preview parser.
    web_source=xml_source/'dlls/windows.web'
    archive=execute(['git','-C',sdk_source,'archive','--format=tar',lock['wineCommit'],'dlls/windows.web'],REPO,True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:tar.extractall(xml_source,filter='data')
    web_objects=output/'web-objects';web_objects.mkdir()
    web_files=re.findall(r'\b([A-Za-z][A-Za-z0-9_]*\.c)\b',(web_source/'Makefile.in').read_text())
    for name in web_files:
        target='dlls/windows.web/x86_64-windows/'+Path(name).stem+'.o';args=[]
        for token in rule(target):
            if token in ['-g','-gdwarf-4']:continue
            if token==target:token=Path(name).stem+'.o'
            elif not token.startswith('-') and (sdk_build/token).resolve()==sdk_source/'dlls/windows.web'/name:token=os.path.relpath(web_source/name,web_objects)
            elif token.startswith('-I'):token=sdk_include(token,sdk_build,sdk_source/'dlls/windows.web',web_source,web_objects)
            args.append(token)
        execute(args+['-ffile-prefix-map='+str(sdk_source)+'=/wine-source'],web_objects,env=env)
    args=[]
    for token in rule('dlls/windows.web/x86_64-windows/windows.web.dll'):
        if token=='-Wl,--build-id':continue
        if token=='dlls/windows.web/x86_64-windows/windows.web.dll':token=relative(output/'windows.web.dll')
        elif not token.startswith('-') and (sdk_build/token).resolve()==sdk_source/'dlls/windows.web/windows.web.spec':token=relative(web_source/'windows.web.spec')
        elif token.startswith('dlls/windows.web/x86_64-windows/') and token.endswith('.o'):token=relative(web_objects/Path(token).name)
        args.append(token)
    execute(args+['-Wl,--no-insert-timestamp','-Wl,--build-id=none'],sdk_build,env=env)
    execute(['x86_64-w64-mingw32-strip','--strip-debug',output/'windows.web.dll'],REPO,env=env)
    return files

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output',type=Path)
    parser.add_argument('--runtime-mirror',required=True,type=Path)
    parser.add_argument('--sdk-source',type=Path)
    parser.add_argument('--sdk-build',type=Path)
    parser.add_argument('--sources-only',action='store_true')
    args=parser.parse_args();lock=json.loads((PACK/'source.lock.json').read_text())
    check(PACK,lock['sources'])
    output=args.output.resolve()
    for forbidden in [PACK, args.sdk_source, args.sdk_build]:
        if forbidden and (output==forbidden.resolve() or forbidden.resolve() in output.parents):raise ValueError('Keep build output outside pack sources and the SDK')
    output.mkdir(parents=True,exist_ok=False)
    reconstruct(args.runtime_mirror.resolve(),output/'runtime-source',lock)
    source=output/'source';shutil.copytree(PACK/'source',source)
    for patch in ['fh5-timestamp.patch','metal4-frequency.patch','clock-reporting.patch']:
        execute(['git','apply',source/'metal4'/patch],source/'shim',env={**os.environ,'GIT_CEILING_DIRECTORIES':str(source)})
    if args.sources_only:
        print('Pinned runtime and owned graphics source reconstructed; no binaries built.');return
    if not args.sdk_source or not args.sdk_build:raise ValueError('Supply the pinned Wine SDK source and generated build')
    payload=output/'payload';payload.mkdir()
    env={key:value for key,value in os.environ.items() if not key.startswith(('XODUS_','XUSER_','WINE','CX_','DYLD_','MACXUS_','NEXUS_'))}
    env['SOURCE_DATE_EPOCH']=str(lock['sourceDateEpoch'])
    toolchain={'mingwGCC':execute(['x86_64-w64-mingw32-gcc','-dumpfullversion'],REPO,True,env).decode().strip(),
               'appleClang':execute(['clang','--version'],REPO,True,env).decode().splitlines()[0],
               'macOSSDK':execute(['xcrun','--sdk','macosx','--show-sdk-version'],REPO,True,env).decode().strip()}
    if toolchain!=lock['toolchain']:raise ValueError('Use the source lock toolchain; other tools require artifact revalidation')
    common=['x86_64-w64-mingw32-gcc','-O2','-Wall','-static-libgcc','-Wl,--no-insert-timestamp']
    # GNU PE linking derives its default image base from the output pathname.
    # Pin it explicitly, and compile relative inputs from the reconstructed
    # source directory so relocations and __FILE__ do not depend on the checkout.
    execute(common+['-shared',*[str(Path('shim')/name) for name in ['d3d12.c','dxil_shadingrate.c','inspect.c','d3d12.def']],
                    '-ffile-prefix-map='+str(output)+'=/fh5-build',
                    '-Wl,--image-base,0x180000000','-o',payload/'d3d12.dll','-lws2_32','-lbcrypt'],source,env=env)
    execute(['x86_64-w64-mingw32-strip','--strip-debug',payload/'d3d12.dll'],REPO,env=env)
    execute(['clang','-arch','x86_64','-mmacosx-version-min=26.0','-fobjc-arc','-dynamiclib','-O2','-Wall','-Wextra','-Werror',source/'metal4/metal4-query-bridge.m','-framework','Foundation','-framework','Metal','-install_name','@rpath/macxus-metal4-timestamps.dylib','-o',payload/'macxus-metal4-timestamps.dylib'],REPO,env=env)
    execute(['clang','-arch','x86_64','-mmacosx-version-min=26.0','-dynamiclib','-O2','-Wall','-Wextra','-Werror','clock/clock-unix.c','-install_name','@rpath/macxus-clock.so','-o',payload/'macxus-clock.so'],source,env=env)
    execute([args.sdk_build.resolve()/'tools/winegcc/winegcc','-b','x86_64-w64-mingw32','--wine-objdir',args.sdk_build.resolve(),'-shared','-Wl,--wine-builtin','-D__WINESRC__','-O2','-Wall','-I'+str(args.sdk_build.resolve()/'include'),'-I'+str(args.sdk_source.resolve()/'include'),'clock/clock-pe.c','clock/macxus-clock.spec','-o',payload/'macxus-clock.dll','-lwinecrt0','-lkernel32','-lntdll','-Wl,--no-insert-timestamp','-Wl,--build-id=none'],source,env=env)
    execute(['x86_64-w64-mingw32-strip','--strip-debug',payload/'macxus-clock.dll'],REPO,env=env)
    objects=output/'runtime-objects';objects.mkdir()
    compiled=compile_runtime(output/'runtime-source',args.sdk_source.resolve(),args.sdk_build.resolve(),objects,lock,env)
    for name in ['xgameruntime.dll','windows.web.dll']:shutil.copyfile(objects/name,payload/name)
    # Ship only our newly built modules. The selected shared runtime supplies its
    # other dependencies; installed vendor DLLs/loaders are never distributed.
    for name in ['d3d12.dll','xgameruntime.dll','windows.web.dll']:
        file=payload/name;raw=bytearray(file.read_bytes())
        if raw[64:80]==b'Wine builtin DLL':raw[64:80]=bytes(16);file.write_bytes(raw)
    receipt={'schema':1,'id':'fh5-preview-v1','sourceLockSHA256':sha(PACK/'source.lock.json'),'runtimeSourceLockSHA256':lock['runtimeSourceLockSHA256'],'toolchain':toolchain,'files':{p.name:sha(p) for p in payload.iterdir()},'compiledRuntimeCFiles':compiled,'gameValidation':'pending portable-pack game trial','gameCodeIncluded':False,'vendorBinariesIncluded':False}
    probes=output/'probes';probes.mkdir()
    for name in ['data-fixture','input-layout-contracts','unused-blend-contracts','gpu-clock-reporting','io-lifetime','stream-debug-contracts','nvapi-profile','nvapi-memory','nvapi-provider','heap-import']:
        helpers=[PACK/'source/shim'/file for file in ['dxil_shadingrate.c','inspect.c']] if name in ['input-layout-contracts','unused-blend-contracts','io-lifetime','stream-debug-contracts'] else []
        execute(common+[PACK/'source/tests'/(name+'.c'),*helpers,'-o',probes/(name+'.exe'),'-lws2_32','-lbcrypt'],REPO,env=env)
    foreign=probes/'foreign';foreign.mkdir()
    execute(common+['-shared',PACK/'source/tests/nvapi-foreign.c','-o',foreign/'nvapi64.dll'],REPO,env=env)
    # Match the pinned PE's size so the negative control exercises SHA256.
    foreign_pe=foreign/'nvapi64.dll'
    if foreign_pe.stat().st_size >= 200256:raise ValueError('Foreign provider fixture is unexpectedly large')
    with foreign_pe.open('ab') as file:file.write(bytes(200256-foreign_pe.stat().st_size))
    sdk_source=args.sdk_source.resolve();sdk_build=args.sdk_build.resolve()
    execute([sdk_build/'tools/winegcc/winegcc','-b','x86_64-w64-mingw32','--wine-objdir',sdk_build,'-D__WINESRC__','-D_UCRT','-DLIBXML_STATIC','-O2','-Wall',
             '-I',sdk_build/'dlls/xgameruntime','-I',output/'runtime-source/dlls/xgameruntime','-I',sdk_build/'include','-I',sdk_source/'include','-isystem',sdk_source/'include/msvcrt','-I',sdk_source/'libs/xml2/include',
             PACK/'source/tests/store-addons-probe.c',objects/'libxml2.a','-o',probes/'store-addons.exe','-lcombase','-lole32','-lcrypt32','-lbcrypt','-lwinhttp','-ladvapi32','-lwinecrt0','-lucrtbase','-lkernel32','-lntdll'],sdk_build,env=env)
    imports=execute(['x86_64-w64-mingw32-objdump','-p',probes/'store-addons.exe'],REPO,True).decode()
    if 'DLL Name: ucrtbase.dll' not in imports or re.search(r'DLL Name: msvcr',imports,re.I):raise ValueError('Store probe CRT mismatch')
    for name in ['metal4-counter-probe','metal4-state-probe','metal4-order-probe','metal4-lifetime-probe']:
        execute(['clang','-arch','x86_64','-mmacosx-version-min=26.0','-fobjc-arc','-O2','-Wall','-Wextra','-Werror',PACK/'source/metal4'/(name+'.m'),'-framework','Foundation','-framework','Metal','-o',probes/name],REPO,env=env)
    execute(common+[PACK/'source/clock/clock-probe.c','-o',probes/'clock-calibration.exe'],REPO,env=env)
    execute(['clang','-arch','x86_64','-mmacosx-version-min=26.0','-fobjc-arc','-O2','-Wall','-Wextra','-Werror',PACK/'source/clock/native-probe.m','-framework','Foundation','-framework','Metal','-o',probes/'clock-native'],REPO,env=env)
    execute(['clang','-O1','-g','-fsanitize=address,undefined','-fno-omit-frame-pointer','-Wall','-Wextra','-Werror',PACK/'source/clock/math-probe.c','-o',probes/'clock-math'],REPO,env=env)
    corresponding=output/'corresponding-source';corresponding.mkdir()
    execute(['git','-C',args.sdk_source.resolve(),'archive','--format=tar.gz','--output='+str(corresponding/'wine-source.tar.gz'),lock['wineCommit']],REPO)
    recipe=corresponding/'recipe';recipe.mkdir()
    for folder in ['scripts/fh5-pack','scripts/runtime-tests','scripts/runtime-compat']:
        shutil.copytree(REPO/folder,recipe/folder,ignore=shutil.ignore_patterns('__pycache__'))
    shutil.copyfile(REPO/'scripts/fh5-pack.mjs',recipe/'scripts/fh5-pack.mjs')
    for patch in json.loads(runtime_lock_file(lock).read_text())['patches']:
        target=recipe/patch['file'];target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(REPO/patch['file'],target)
    shutil.copytree(PACK,recipe/'assets/fh5-preview',ignore=shutil.ignore_patterns('payload','source-release','manifest.json'))
    # Verification needs the candidate/engine pins, but including the final
    # manifest would recursively embed this archive's own hash.
    metadata=PACK/'manifest.json'
    if not metadata.exists():metadata=PACK/'verification.json'
    manifest=json.loads(metadata.read_text())
    if metadata.name=='verification.json' and (manifest.get('sourceReleaseDescriptor')!=1 or 'sourceArchive' in manifest):raise ValueError('Invalid source-release build descriptor')
    descriptor=verification_descriptor(manifest,receipt)
    (recipe/'assets/fh5-preview/verification.json').write_text(json.dumps(descriptor,indent=2,sort_keys=True)+'\n')
    archive=output/'fh5-preview-v1-source.tar.gz'
    with archive.open('wb') as raw,gzip.GzipFile(fileobj=raw,mode='wb',mtime=lock['sourceDateEpoch'],filename='') as zipped,tarfile.open(fileobj=zipped,mode='w') as tar:
        for folder in ['source','runtime-source','corresponding-source']:
            for file in sorted((output/folder).rglob('*')):
                if not file.is_file():continue
                info=tar.gettarinfo(file,arcname=str(file.relative_to(output)));info.uid=info.gid=0;info.uname=info.gname='';info.mode=0o644;info.mtime=lock['sourceDateEpoch']
                with file.open('rb') as data:tar.addfile(info,data)
    receipt['sourceArchive']={'name':archive.name,'sha256':sha(archive)}
    (output/'build.json').write_text(json.dumps(receipt,indent=2)+'\n')
    for license in ['COPYING.GPL-3.0','COPYING.LGPL-2.1']:shutil.copyfile(PACK/license,output/license)
    print('Built source pack; no installation, account access or game launch performed.')

if __name__=='__main__':main()
